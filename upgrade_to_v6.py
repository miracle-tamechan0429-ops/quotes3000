    episodes = json.loads(EPISODES_PATH.read_text(encoding="utf-8"))
    for ep in episodes:
        eid = ep["id"]
        if eid in V6_UPDATES:
            upd = V6_UPDATES[eid]
            ep["slide1"] = upd["slide1"]
            ep["slide2"] = upd["slide2"]
            ep["slide3"] = upd["slide3"]
            ep["slide4"] = upd["slide4"]
            ep["slide5"] = upd["slide5"]
            ep["tiktok"] = upd["tiktok"]

    EPISODES_PATH.write_text(json.dumps(episodes, ensure_ascii=False, indent=2), encoding="utf-8")
    print("[OK] Updated episodes.json (008-016) to Viral v6.2 High-Visibility structure.")

    for ep in episodes:
        eid = ep["id"]
        if eid in V6_UPDATES:
            bg_path = WORKSPACE_DIR / "backgrounds" / f"{eid}_bg.png"
            out_dir = WORKSPACE_DIR / "posts" / f"{eid}_{ep['theme']}"
            render_slides.render_episode(ep, out_dir, bg_path if bg_path.exists() else None)
            print(f"[RENDERED v6.2] Episode {eid} -> {out_dir}")

    today_jst = cloud_send_daily.get_today_jst()
    ep007 = next((e for e in episodes if e["id"] == "007"), None)
    cloud_send_daily.update_docs_index(episodes, ep007, today_jst)
    print("[OK] Updated docs/index.html with v6.2 captions and comments.")


